#!/usr/bin/env python3
"""TPC-H Q17: query time and Bloom filter / decoder throughput over the scale factor.

    ./sweep_tpch_q17.py                                    # a new folder results/tpch_q17_<date>_<time>
    ./sweep_tpch_q17.py --resume results/tpch_q17_20261014_101530   # continue that experiment

runs TPC-H Q17 (bench.py's statistics, tpch_bench.py's data) at the scale factors 1 ... 8 (--scale-factors),
one after the other, with everything else at the defaults of bench.py. Then it plots the results (plot_utils.py).
The experiment folder has the structure of the other sweeps, with the scale factor as the points:

    results/tpch_q17_<date>_<time>/
        results/bloom_on/sf1/ ... sf8/                    one folder per point, as written by bench.py
        results/bloom_off/sf1/ ...                        the same points with the Bloom filter off
        results/summary.csv                               one row per point, both variants side by side
        plots/bloom_on/, plots/bloom_off/                 one plot per measure and variant
        plots/both/                                       both variants in one picture per measure,
                                                          and query_breakdown.pdf

The measures are the ones of every sweep (sweep_lib.py): query, scan and rest time (the host's wall clock),
the decoder's input and output throughput, its starved / stalled cycles and waiting share, and the Bloom filter's
input and output throughput. Every point is the median over the measured runs (--agg changes that).

The query is Q17 with the predicate of its build side removed:

    SELECT sum(l_extendedprice) / 7.0 AS avg_yearly
    FROM lineitem, part
    WHERE p_partkey = l_partkey
      AND l_quantity < (SELECT 0.2 * avg(l_quantity) FROM lineitem l2 WHERE l2.l_partkey = p_partkey)

where `part` is a file that holds only the parts of the original predicate (p_brand = 'Brand#23' AND p_container
= 'MED BOX': 0.1% of the parts). The hardware Bloom filter is built from the whole key column of the build file, so
a predicate in the query would never narrow it: with the file pre-filtered the filter holds exactly the keys the
predicate selects, and the probe side, lineitem, is pruned down to the 0.1% of its rows that join. The answer of every
run is checked against the original query (predicate in the WHERE clause) on the tables dbgen generated.

With the predicate gone, DuckDB's `deliminator` pass would reshape the query so that no join between a lineitem scan
and the part scan is left for the Bloom filter (the extension then logs "join skipped"). It is switched off for
both variants (SET disabled_optimizers = 'deliminator'), so their plans are the same.

Lineitem is scanned twice by the query: by the join (l_partkey, l_quantity, l_extendedprice: this is the scan the
Bloom filter prunes) and by the subquery's aggregate (l_partkey, l_quantity: not pruned, it needs every row). The
decoder's throughput is therefore that of the scans of lineitem together, from the first one's start to the end of
the query (tpch_bench.py, TpchWorkload.probe_segments); the Bloom filter's is that of its one run, as always.

--bloom {on,off,both} (default: both) chooses the variants: the hardware Bloom filter on, off (then DuckDB's own join Bloom filter filters the scans), or both,
which runs the two variants of a point back to back and plots them side by side (plots/both/). Bloom off has no
Bloom filter throughput (bloom_in, bloom_out), so those are only plotted for on.

The TPC-H data is generated by DuckDB's dbgen (the duckdb package with the tpch extension) into a temporary
directory (--tmp-dir) when a point needs it, for both variants, and removed when the point is done. Every column
is OPTIONAL without NULLs, as ParCore needs it (about 0.4 GB per scale factor uncompressed, with 16 columns of
lineitem). --compression snappy writes Snappy compressed files.

The sweep stops at the first failure. Run it again with `--resume <experiment folder>` to continue: complete points
are skipped, and the folder of a failed point (kept for its logs) has to be removed first. `--resume FOLDER
--plots-only` plots what is there without running.
"""

import sys

import sweep_lib
import tpch_bench

SWEEP, add_args, points_of = tpch_bench.scale_factor_sweep(tpch_bench.Q17, "sweep_tpch_q17.py", __doc__)


if __name__ == "__main__":
    sys.exit(sweep_lib.main(SWEEP, add_args, points_of))
