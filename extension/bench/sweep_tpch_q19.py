#!/usr/bin/env python3
"""TPC-H Q19: query time and Bloom filter / decoder throughput over the scale factor.

    ./sweep_tpch_q19.py                                    # a new folder results/tpch_q19_<date>_<time>
    ./sweep_tpch_q19.py --resume results/tpch_q19_20261014_101530   # continue that experiment

runs TPC-H Q19 (bench.py's statistics, tpch_bench.py's data) at the scale factors 1 ... 8 (--scale-factors),
one after the other, with everything else at the defaults of bench.py. Then it plots the results (plot_utils.py).
The experiment folder has the structure of the other sweeps, with the scale factor as the points:

    results/tpch_q19_<date>_<time>/
        results/bloom_on/sf1/ ... sf8/                    one folder per point, as written by bench.py
        results/bloom_off/sf1/ ...                        the same points with the Bloom filter off
        results/summary.csv                               one row per point, both variants side by side
        plots/bloom_on/, plots/bloom_off/                 one plot per measure and variant
        plots/both/                                       both variants in one picture per measure,
                                                          and query_breakdown.pdf

The measures are the ones of every sweep (sweep_lib.py): query, scan and rest time (the host's wall clock),
the decoder's input and output throughput, its starved / stalled cycles and waiting share, and the Bloom filter's
input and output throughput. Every point is the median over the measured runs (--agg changes that).

The query is Q19 with the part predicates that the pre-filtered file implies removed:

    SELECT sum(l_extendedprice * (1 - l_discount)) AS revenue
    FROM lineitem, part
    WHERE p_partkey = l_partkey
      AND l_shipmode IN ('AIR', 'AIR REG') AND l_shipinstruct = 'DELIVER IN PERSON'
      AND ((p_brand = 'Brand#12' AND l_quantity >= 1  AND l_quantity <= 1 + 10)
        OR (p_brand = 'Brand#23' AND l_quantity >= 10 AND l_quantity <= 10 + 10)
        OR (p_brand = 'Brand#34' AND l_quantity >= 20 AND l_quantity <= 20 + 10))

where `part` is a file that holds only the parts that satisfy the part predicate of one of the three groups of the
original query (p_brand = 'Brand#12' AND p_container IN ('SM CASE', ...) AND p_size BETWEEN 1 AND 5, and the two
others for Brand#23 and Brand#34). The hardware Bloom filter is built from the whole key column of the build
file, so it holds exactly the keys of those parts (about 0.24 % of `part`) and the probe side, lineitem, is pruned
to the rows of those parts.

What left the query, and what stayed (the answer of every run is checked against the original query on the tables
dbgen generated, so a wrong decision shows as a failed run, and test_tpch.py checks it at scale factor 0.1):

* The disjunction of the three groups' part predicates is the file's filter: a part that satisfies none of them
  cannot be in the result.
* The groups' part predicates are mutually exclusive, because their brands differ. A part of the file therefore
  satisfies exactly one group's part predicate, and p_brand says which. So p_container and p_size, which that
  group's predicate has as well, are implied by the file and p_brand, and are not in the query any more.
* p_brand stays: it couples each part to its group's l_quantity range (a part of Brand#12 with a quantity in
  10..20 does not qualify). That coupling mixes columns of both sides, it cannot be a filter of one file.
* The probe side's own predicates stay in the query: l_quantity ranges, l_shipmode, l_shipinstruct. The two that every
  group has are written once, outside the OR (what DuckDB's plan does with the original as well).

DuckDB's plan needs no setting for the extension to find the lineitem-part join (checked with EXPLAIN and
the extension's debug log: "Runtime Bloom filter rewrite": build side part_q19.parquet, probe side lineitem). The
OR with the three groups is evaluated as a condition of the hash join, over the rows the Bloom filter kept.

Lineitem is scanned once. The decoder's output is the four 8 byte columns the query reads (l_partkey, l_quantity,
l_extendedprice, l_discount); l_shipmode and l_shipinstruct are strings, which the extension decodes on the CPU,
so they are not in the decoder's throughput (tpch_bench.py, TpchWorkload.check_run checks the decoder's output
bytes against that). The pushed-down filters on lineitem are applied after the decoder, whole columns are decoded.

--bloom {on,off,both} (default: both) chooses the variants: the hardware Bloom filter on, off (then DuckDB's own join Bloom filter filters the scans), or both,
which runs the two variants of a point back to back and plots them side by side (plots/both/). Bloom off has no
Bloom filter throughput (bloom_in, bloom_out), so those are only plotted for on.

The TPC-H data is generated by DuckDB's dbgen (the duckdb package with the tpch extension) into a temporary
directory (--tmp-dir) when a point needs it, for both variants, and removed when the point is done. Every column
is OPTIONAL without NULLs, as ParCore needs it (about 0.4 GB per scale factor uncompressed, with 16 columns of
lineitem). --compression snappy writes Snappy compressed files.

The sweep stops at the first failure. Run it again with `--resume <experiment folder>` to continue: complete points
are skipped, and the folder of a failed point (kept for its logs) has to be removed first. `--resume FOLDER
--plots-only` plots what is there without running.
"""

import sys

import sweep_lib
import tpch_bench

SWEEP, add_args, points_of = tpch_bench.scale_factor_sweep(tpch_bench.Q19, "sweep_tpch_q19.py", __doc__)


if __name__ == "__main__":
    sys.exit(sweep_lib.main(SWEEP, add_args, points_of))
